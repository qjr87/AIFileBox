function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    params[key] !== undefined ? String(params[key]) : `{${key}}`,
  )
}

const LOCALE_INDEX: Record<Exclude<LocaleId, 'zh-CN'>, number> = {
  'zh-TW': 0,
  en: 1,
  ja: 2,
  ko: 3,
  es: 4,
  fr: 5,
  de: 6,
}

export function translateWithLocale(
  locale: LocaleId,
  zhKey: string,
  params?: Record<string, string | number>,
): string {
  if (locale === 'zh-CN') {
    return interpolate(zhKey, params)
  }
  const entry = DICT[zhKey]
  if (entry) {
    const idx = LOCALE_INDEX[locale]
    const translated = entry[idx] ?? zhKey
    return interpolate(translated, params)
  }
  return interpolate(zhKey, params)
}

type I18nContextValue = {
  locale: LocaleId
  setLocale: (next: LocaleId) => void
  t: (zhKey: string, params?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nContextValue>({
  locale: 'zh-CN',
  setLocale: () => {},
  t: (zhKey, params) => interpolate(zhKey, params),
})

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<LocaleId>(() => detectInitialLocale())

  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])

  const setLocale = useCallback((next: LocaleId) => {
    setLocaleState(next)
    try {
      window.localStorage.setItem(STORAGE_KEY, next)
      const prev = JSON.parse(window.localStorage.getItem('archive-desk-settings') || '{}') as Record<string, unknown>
      window.localStorage.setItem('archive-desk-settings', JSON.stringify({ ...prev, locale: next }))
    } catch {
      // ignore storage errors
    }
  }, [])

  const t = useCallback(
    (zhKey: string, params?: Record<string, string | number>) => translateWithLocale(locale, zhKey, params),
    [locale],
  )

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  return useContext(I18nContext)
}
