export type LocaleId = 'zh-CN' | 'zh-TW' | 'en' | 'ja' | 'ko' | 'es' | 'fr' | 'de'

export type LocaleOption = {
  id: LocaleId
  label: string
  nativeName: string
  shortTag: string
}

export const SUPPORTED_LOCALES: LocaleOption[] = [
  { id: 'zh-CN', label: '简体中文', nativeName: '简体中文', shortTag: '简中' },
  { id: 'zh-TW', label: '繁體中文', nativeName: '繁體中文', shortTag: '繁中' },
  { id: 'en', label: 'English', nativeName: 'English', shortTag: 'EN' },
  { id: 'ja', label: '日本語', nativeName: '日本語', shortTag: 'JA' },
  { id: 'ko', label: '한국어', nativeName: '한국어', shortTag: 'KO' },
  { id: 'es', label: 'Español', nativeName: 'Español', shortTag: 'ES' },
  { id: 'fr', label: 'Français', nativeName: 'Français', shortTag: 'FR' },
  { id: 'de', label: 'Deutsch', nativeName: 'Deutsch', shortTag: 'DE' },
]

const STORAGE_KEY = 'archive-desk-lang'

export function detectInitialLocale(): LocaleId {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY) as LocaleId | null
    if (saved && SUPPORTED_LOCALES.some((item) => item.id === saved)) {
      return saved
    }
    const settingsRaw = window.localStorage.getItem('archive-desk-settings')
    if (settingsRaw) {
      const parsed = JSON.parse(settingsRaw) as { locale?: string }
      if (parsed.locale && SUPPORTED_LOCALES.some((item) => item.id === parsed.locale)) {
        return parsed.locale as LocaleId
      }
    }
    const nav = (navigator.language || '').toLowerCase()
    if (nav.startsWith('zh-tw') || nav.startsWith('zh-hk') || nav.startsWith('zh-mo') || nav.includes('hant')) return 'zh-TW'
    if (nav.startsWith('zh')) return 'zh-CN'
    if (nav.startsWith('ja')) return 'ja'
    if (nav.startsWith('ko')) return 'ko'
    if (nav.startsWith('es')) return 'es'
    if (nav.startsWith('fr')) return 'fr'
    if (nav.startsWith('de')) return 'de'
    if (nav.startsWith('en')) return 'en'
  } catch {
    // ignore storage errors
  }
  return 'zh-CN'
}

